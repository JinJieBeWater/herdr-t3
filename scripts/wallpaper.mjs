// Writes extras/mods/asciicn-wallpaper/scenes.js and scenes/: the built-in pictures, asciicn's (MIT, https://asciicn.dev), as
// one-colour SVG tiles the mod tints with the theme, converted by the mod's own ascii-art.js, as an import is.
//   node scripts/wallpaper.mjs <folder of <scene>.ans>
// Each <scene>.ans is one truecolor frame of that asciicn component, drawn 2317 by 959 px with `charset="dots"`,
// `colorMode="truecolor"`, `cell={7}` and, where the component passes it on, `square`, then saved with asciicn's
// `toAnsi(handle.capture())`. That makes 331 by 137 square cells; Mountain dusk keeps asciicn's narrow cells (773
// across), so the aspect (a cell's width over its height) comes from the frame's size here, not ascii-art's guess.
// The Studio exports Lighthouse; Ember, Nebula and Mountain dusk need asciicn run locally.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { convert } from "../extras/mods/asciicn-wallpaper/ascii-art.js";

// Name, and where the subject is across the picture (0 left, 1 right): that point stays put as the pane's width changes.
const SCENES = {
  lighthouse: ["Lighthouse", 0.73], "mountain-dusk": ["Mountain dusk", 0.5], nebula: ["Nebula", 0.5], ember: ["Ember", 0.5],
};
const FRAME = { width: 2317, height: 959 };

const dir = process.argv[2], out = new URL("../extras/mods/asciicn-wallpaper/", import.meta.url);
rmSync(new URL("scenes/", out), { recursive: true, force: true });
const list = [];
for (const [id, [name, focus]] of Object.entries(SCENES)) {
  const text = readFileSync(`${dir}/${id}.ans`, "utf8"), lines = text.split("\n").filter((l) => l !== "");
  const columns = Math.max(...lines.map((l) => [...l.replace(/\x1b\[[0-9;]*m/g, "")].length));
  const it = convert(text, +((FRAME.width / columns) / (FRAME.height / lines.length)).toFixed(3)), tiles = [];
  mkdirSync(new URL(`scenes/${id}/`, out), { recursive: true });
  let step;
  while (!(step = it.next()).done) {
    if (!step.value) continue;
    const { svg, ...tile } = step.value;
    writeFileSync(new URL(`scenes/${id}/${tile.file}`, out), svg);
    tiles.push(tile);
  }
  list.push({ id, name, focus, width: step.value.width, height: step.value.height, tiles });
  console.log(`${id}: ${columns}x${lines.length}, aspect ${step.value.aspect}, ${tiles.length} tiles`);
}
writeFileSync(new URL("scenes.js", out), `// Generated by scripts/wallpaper.mjs. Do not edit by hand.\nexport const SCENES = ${JSON.stringify(list)};\n`);
