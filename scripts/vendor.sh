#!/bin/sh
# Builds what the mods carry from outside, at pinned versions; the output is committed, so installing needs no bun:
#   - mods/t3-files/vendor/ufuzzy.js: uFuzzy (package.json's version) as one ESM file.
#   - shared/file-icons-data.js and shared/icons/cat/: catppuccin/vscode-icons' name, extension and folder matches, and the
#     SVGs they name, for shared/file-icons.js. scripts/sync.sh copies both to the mods that draw file icons.
#   - extras/mods/review/vendor/char-width.js: each code point's columns, from get-east-asian-width (package.json's version)
#     and Unicode's mark and default-ignorable properties, for rows.js's charWidth.
# Run it only to move a version; then scripts/sync.sh and scripts/check.sh.
set -eu
src=$(cd "$(dirname "$0")/.." && pwd)
CAT_REV=b6915da9f6889b683a110aa747de96c2820a537d # catppuccin/vscode-icons v1.26.0, 2025-10-12
FLAVOR=macchiato # the one Review drew before (pulls.review's, through @iconify-json/catppuccin)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# Installed beside, not here: no node_modules or lockfile in the repo.
cp "$src/package.json" "$tmp/"
(cd "$tmp" && bun install --silent)
out=$src/mods/t3-files/vendor
mkdir -p "$out"
bun build "$tmp/node_modules/@leeoniya/ufuzzy/dist/uFuzzy.mjs" --format esm --outfile "$tmp/ufuzzy.js" >/dev/null
# Bun's first line names the temp folder it built from. Not type-checked: it's theirs.
{ echo "// @ts-nocheck"; echo "// @leeoniya/ufuzzy $(jq -r .version "$tmp/node_modules/@leeoniya/ufuzzy/package.json"), bundled by scripts/vendor.sh: don't edit."; tail -n +2 "$tmp/ufuzzy.js"; } > "$out/ufuzzy.js"
cp "$tmp/node_modules/@leeoniya/ufuzzy/LICENSE" "$out/LICENSE-ufuzzy"

out=$src/extras/mods/review/vendor
mkdir -p "$out"
cat > "$tmp/width.ts" <<'EOF'
import { eastAsianWidth } from "get-east-asian-width";
const [out, version] = process.argv.slice(2);
// As wcwidth: marks drawn on the character before and what's never drawn take 0; else East Asian Wide or Fullwidth 2, others 1.
const zero = /^[\p{Mn}\p{Me}\p{Default_Ignorable_Code_Point}]$/u;
const starts: number[] = [], widths: number[] = [];
for (let cp = 0; cp <= 0x10ffff; cp++) {
  const w = zero.test(String.fromCodePoint(cp)) ? 0 : eastAsianWidth(cp);
  if (widths.at(-1) !== w) { starts.push(cp); widths.push(w); }
}
await Bun.write(out, `// Generated by scripts/vendor.sh from get-east-asian-width ${version} (Unicode's East Asian Width) and Unicode's Mn, Me and
// Default_Ignorable_Code_Point (as Bun ${Bun.version} has them): don't edit. From STARTS[i] to the next start, a code point is WIDTHS[i] columns.
export const STARTS = ${JSON.stringify(starts)};
export const WIDTHS = ${JSON.stringify(widths)};
`);
console.log(`${starts.length} width runs`);
EOF
(cd "$tmp" && bun width.ts "$out/char-width.js" "$(jq -r .version node_modules/get-east-asian-width/package.json)")
cp "$tmp/node_modules/get-east-asian-width/license" "$out/LICENSE-get-east-asian-width"

git clone -q --filter=blob:none https://github.com/catppuccin/vscode-icons.git "$tmp/cat"
git -C "$tmp/cat" checkout -q "$CAT_REV"
cat > "$tmp/gen.ts" <<'EOF'
import { fileExtensions, fileNames } from "./cat/src/defaults/fileIcons.ts";
import { folderNames } from "./cat/src/defaults/folderIcons.ts";
import { copyFileSync, existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
const [cat, src, flavor, rev] = process.argv.slice(2);
const low = (o: Record<string, string>) => Object.fromEntries(Object.entries(o).map(([k, v]) => [k.toLowerCase(), v]));
const names = low(fileNames), exts = low(fileExtensions), folders = low(folderNames);
const icons = new Set(["_file", "_folder", "_folder_open", ...Object.values(names), ...Object.values(exts),
  ...Object.values(folders).flatMap(f => [f, `${f}_open`])]);
const dir = `${src}/shared/icons/cat`;
rmSync(dir, { recursive: true, force: true });
mkdirSync(dir, { recursive: true });
for (const i of icons) {
  const from = `${cat}/icons/${flavor}/${i}.svg`;
  if (!existsSync(from)) throw new Error(`no icon ${i} in ${flavor}`);
  copyFileSync(from, `${dir}/${i}.svg`);
}
copyFileSync(`${cat}/LICENSE`, `${dir}/LICENSE`);
writeFileSync(`${src}/shared/file-icons-data.js`, `// Generated by scripts/vendor.sh from catppuccin/vscode-icons ${rev}: don't edit. Keys are lowercase; values name icons/cat/<value>.svg.
export const FILE_NAMES = ${JSON.stringify(names)};
export const FILE_EXTENSIONS = ${JSON.stringify(exts)};
export const FOLDER_NAMES = ${JSON.stringify(folders)};
`);
console.log(`${icons.size} icons`);
EOF
(cd "$tmp" && bun gen.ts "$tmp/cat" "$src" "$FLAVOR" "$CAT_REV")
